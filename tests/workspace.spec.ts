  await expect(modal.getByRole('alert')).toContainText('http/https')
  await modal.getByRole('textbox').fill('https://example.com/unfetched-demo')
  await modal.getByRole('button', { name: 'เพิ่มลิงก์' }).click()
  await expect(page.getByText('example.com', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'ลบ example.com' }).click()
  const upload = page.getByLabel('แนบรูปภาพ', { exact: true })
  await upload.setInputFiles({ name: 'large.png', mimeType: 'image/png', buffer: Buffer.alloc(5 * 1024 * 1024 + 1) })
  await expect(page.getByRole('alert')).toContainText('5 MB')
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aF9sAAAAASUVORK5CYII=', 'base64')
  await upload.setInputFiles({ name: 'sample.png', mimeType: 'image/png', buffer: png })
  await expect(page.getByRole('img', { name: 'ภาพแนบ sample.png' })).toBeVisible()
