import { test, expect, type Page } from '@playwright/test'

async function send(page: Page, text: string) { await page.getByRole('textbox', { name: 'ข้อความถึง CIC' }).fill(text); await page.getByRole('button', { name: 'ส่งข้อความ', exact: true }).click() }
async function selectSource(page: Page, label = 'หน้าต่างโปรแกรม') {
  await page.getByRole('button', { name: 'ลองเลือกหน้าจอ', exact: true }).click()
  await page.getByRole('dialog', { name: 'ลองเลือกหน้าจอ', exact: true }).getByRole('button', { name: new RegExp(label) }).click()
  await expect(page.getByRole('dialog', { name: 'ลองเลือกหน้าจอ', exact: true })).not.toBeVisible()
}
test('hash routes, direct refresh, history, landing anchors, and app avoids Three.js', async ({ page }) => {
  const loaded: string[] = [], errors: string[] = []
  page.on('request', request => loaded.push(request.url()))
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('./#/app')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('วันนี้อยากให้ CIC')
  expect(loaded.some(url => /\/Scene-.*\.js/.test(url))).toBe(false)
  expect(await page.locator('canvas').count()).toBe(0)
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'ข้อความถึง CIC' })).toBeVisible()
  await page.getByRole('link', { name: 'กลับหน้าแนะนำ', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('ช่วยคิดไปกับทุกงาน')
  await page.getByRole('navigation', { name: 'เมนูหลัก' }).getByRole('link', { name: 'รู้จัก CIC', exact: true }).click()
  await expect(page).toHaveURL(/#about$/)
  await expect(page.locator('#about')).toBeInViewport()
  await page.getByRole('button', { name: 'เข้าใช้งาน', exact: true }).first().click()
  await expect(page).toHaveURL(/#\/app$/)
  await page.goBack(); await expect(page.locator('#about')).toBeInViewport()
  await page.goForward(); await expect(page.getByRole('textbox', { name: 'ข้อความถึง CIC' })).toBeVisible()
  expect(errors).toEqual([])
})
test('suggestions, Enter/Shift+Enter/IME, session history and layout share messages and drafts', async ({ page }) => {
  await page.goto('./#/app')
  const input = page.getByRole('textbox', { name: 'ข้อความถึง CIC' })
  await page.getByRole('button', { name: 'วางแผนงาน', exact: true }).click()
  await expect(input).toHaveValue(/ช่วยวางแผน/)
  expect(await page.getByRole('article').count()).toBe(0)
  await input.press('Shift+Enter'); await expect(input).toHaveValue(/\n$/)
  await input.dispatchEvent('compositionstart')
  await input.press('Enter'); expect(await page.getByRole('article').count()).toBe(0)
  await input.dispatchEvent('compositionend'); await input.press('Enter')
  await expect(page.getByRole('article', { name: 'คำตอบจำลอง CIC' })).toHaveCount(1)
  await input.fill('ร่างที่ยังไม่ส่ง')
  await page.getByRole('button', { name: 'มุมมองกะทัดรัด', exact: true }).click()
  await expect(input).toHaveValue('ร่างที่ยังไม่ส่ง')
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.getByRole('button', { name: 'กลับ Workspace' }).click()
  await page.getByRole('button', { name: 'แชตใหม่', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(0)
  await send(page, 'อีกแชตหนึ่ง')
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.getByRole('button', { name: /เปิดแชต ช่วยวางแผน/ }).click()
  await expect(input).toHaveValue('ร่างที่ยังไม่ส่ง')
  await expect(page.getByRole('article')).toHaveCount(2)
  await expect(page.getByRole('article', { name: 'ข้อความของคุณ' })).not.toContainText('อีกแชตหนึ่ง')
})
