test('reading older messages stays put when a reply arrives; latest-message button resumes following', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 600 })
  await page.goto('./#/app')
  const chat = page.getByLabel('ข้อความในแชต', { exact: true })
  await send(page, 'งาน\n'.repeat(40))
  await expect(page.getByRole('article')).toHaveCount(2)
  await send(page, 'คำถามถัดไป')
  await chat.evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')) })
  await expect(page.getByRole('article')).toHaveCount(4)
  await expect(page.getByRole('button', { name: 'ข้อความใหม่ ↓' })).toBeVisible()
  expect(await chat.evaluate(el => el.scrollTop)).toBe(0)
  await page.getByRole('button', { name: 'ข้อความใหม่ ↓' }).click()
  await expect.poll(() => chat.evaluate(el => el.scrollHeight - el.scrollTop - el.clientHeight)).toBeLessThan(5)
})
test('app motion, rapid modal reopen and context toggle keep composer position', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('./#/app')
  const input = page.getByRole('textbox', { name: 'ข้อความถึง CIC' })
  const before = await input.boundingBox()
  await page.getByRole('button', { name: 'ซ่อนบริบท', exact: true }).click()
  const hidden = await input.boundingBox()
  expect(hidden).toEqual(before)
  await page.getByRole('button', { name: 'เปิดบริบท', exact: true }).click()
  await page.getByRole('button', { name: 'ลิงก์', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'แนบลิงก์' })
  expect(await modal.evaluate(el => el.getAnimations().some(a => a.effect?.getTiming().duration === 260))).toBe(true)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'ลิงก์', exact: true }).click()
  await expect(modal.getByRole('button', { name: 'ปิดแนบลิงก์' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(input).toBeVisible()
})
